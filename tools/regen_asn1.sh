#!/usr/bin/env bash
#
# Regenerate the ASN.1 C code in src/asn from the specifications in asn1-definitions.
#
#   tools/regen_asn1.sh              # all three protocols
#   tools/regen_asn1.sh rrc          # just one
#   tools/regen_asn1.sh ngap xnap
#
# Everything under src/asn is generated. Nothing in there is hand-edited, and this script
# is the only supported way to change it -- see docs/ASN1_R18_Migration_Plan.md for how the
# tree got that way and why it must stay that way.
#
# Two invariants this script enforces, because breaking either one produces bugs that do
# not show up until something decodes wrongly at runtime:
#
#   1. One runtime. All three protocol trees compile against the single copy of the asn1c
#      skeletons in src/asn/asn1c. A private per-protocol copy shadows it on the include
#      path and silently gives that protocol a different asn_TYPE_descriptor_t layout than
#      the runtime it links against. tools/check_asn1_runtime.sh checks for this too.
#   2. One compiler. All three trees are generated by the same asn1c build, so their
#      descriptors share an ABI.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# The compiler is a fork: -fprefix prefixes C identifiers (not just filenames), the
# skeletons carry an APER codec, and value assignments are emitted as constants. Stock
# asn1c 0.9.29 will produce a tree that does not compile here.
ASN1C_REPO="${ASN1C_REPO:-/home/joe/repos/asn1c-r18}"
ASN1C_COMMIT="bd8605150035729618dbc9ecd3fb90aaed63bd2a"   # prefix-identifiers-and-aper
ASN1C="$ASN1C_REPO/asn1c/asn1c"
SKELETONS="$ASN1C_REPO/skeletons"

# Identical for every protocol. Notable choices:
#   -fcompound-names    disambiguates same-named types from different modules
#   -findirect-choice   CHOICE members are pointers; call sites depend on this
#   -fhave_native64     ranges up to 64 bits generate as long instead of INTEGER_t
#   -fprefix=           per-protocol C identifier prefix; the three trees link together
#   -fcommon=asn1c      shared runtime lands in <-D>/../asn1c, i.e. src/asn/asn1c
#   -no-gen-OER         nothing here speaks OER
#
# asn1c records its argv verbatim in the preamble of every file it writes, so the *order*
# of these flags is part of the output. Keep the split below as it is: it reproduces the
# command already recorded in the checked-in tree, which is what makes "regenerate, expect
# no diff" a usable check. Reordering them rewrites 10392 files with no change of substance.
FLAGS_PRE=(
    -fcompound-names
    -pdu=all
    -findirect-choice
    -fno-include-deps
    -fhave_native64
    -no-gen-example
    -S "$SKELETONS"
)
FLAGS_POST=(
    -fcommon=asn1c
    -no-gen-OER
)

# protocol : source specification : identifier prefix
PROTOCOLS=(
    "rrc:asn1-definitions/rrc-rel18-v18_9.asn1:ASN_RRC_"
    "ngap:asn1-definitions/ngap-rel18-v18_9.asn1:ASN_NGAP_"
    "xnap:asn1-definitions/xnap-rel18-v18_8.asn1:ASN_XNAP_"
)

die() { printf 'regen_asn1: %s\n' "$*" >&2; exit 1; }

[[ -x "$ASN1C" ]] || die "compiler not built at $ASN1C (set ASN1C_REPO, then run ./configure && make in it)"

actual_commit="$(git -C "$ASN1C_REPO" rev-parse HEAD 2>/dev/null || echo unknown)"
if [[ "$actual_commit" != "$ASN1C_COMMIT" ]]; then
    printf 'regen_asn1: WARNING: %s is at %s, expected %s\n' \
        "$ASN1C_REPO" "${actual_commit:0:12}" "${ASN1C_COMMIT:0:12}" >&2
    printf '            Output may differ from the checked-in tree.\n' >&2
fi
if [[ -n "$(git -C "$ASN1C_REPO" status --porcelain 2>/dev/null)" ]]; then
    printf 'regen_asn1: WARNING: %s has uncommitted changes\n' "$ASN1C_REPO" >&2
fi

selected=("$@")
[[ ${#selected[@]} -eq 0 ]] && selected=(rrc ngap xnap)

# src/asn/asn1c is the shared runtime and is byte-identical to the fork's skeletons, so
# every generation rewrites it with the same bytes. Snapshot it anyway: if that ever stops
# being true, we want to fail loudly rather than quietly relicense the runtime.
runtime_before="$(mktemp -d)"
cp -a src/asn/asn1c "$runtime_before/"

# Each protocol directory has one hand-written file, CMakeLists.txt, and regeneration wipes
# the directory to get there. Restore it however this script exits -- a failed generation
# must not leave the tree unbuildable.
cmakelists=""
cmakelists_dest=""
restore() {
    local rc=$?
    if [[ -n "$cmakelists" && -f "$cmakelists" && -n "$cmakelists_dest" ]]; then
        mkdir -p "$(dirname "$cmakelists_dest")"
        cp "$cmakelists" "$cmakelists_dest"
        printf 'regen_asn1: restored %s\n' "$cmakelists_dest" >&2
    fi
    rm -f "$cmakelists"
    rm -rf "$runtime_before"
    return $rc
}
trap restore EXIT

for name in "${selected[@]}"; do
    entry=""
    for candidate in "${PROTOCOLS[@]}"; do
        [[ "${candidate%%:*}" == "$name" ]] && entry="$candidate"
    done
    [[ -n "$entry" ]] || die "unknown protocol '$name' (expected one of: rrc ngap xnap)"

    IFS=: read -r proto spec prefix <<<"$entry"
    outdir="src/asn/$proto"
    [[ -f "$spec" ]] || die "missing specification $spec"

    printf '=== %s: %s -> %s\n' "$proto" "$spec" "$outdir"

    # The CMakeLists.txt is hand-written (a glob over ASN_<PROTO>_*.[ch]); everything else
    # in the directory is generated and goes.
    cmakelists="$(mktemp)"
    cmakelists_dest="$outdir/CMakeLists.txt"
    cp "$cmakelists_dest" "$cmakelists"
    rm -rf "$outdir"
    mkdir -p "$outdir"

    # asn1c prompts before overwriting the shared runtime directory; answer yes. Paths are
    # relative to the repository root on purpose, so the command recorded in the preamble of
    # every generated file is one that can be re-run verbatim from here.
    # `yes` is killed by SIGPIPE when asn1c exits, so read the compiler's own status out of
    # PIPESTATUS rather than letting pipefail report the producer's death as a failure.
    set +o pipefail
    yes y | "$ASN1C" "${FLAGS_PRE[@]}" -D "$outdir" -fprefix="$prefix" "${FLAGS_POST[@]}" "$spec" \
        > /dev/null 2>"$outdir/.regen.log"
    status=${PIPESTATUS[1]}
    set -o pipefail
    if [[ $status -ne 0 ]]; then
        sed -n '/[Ee]rror/p' "$outdir/.regen.log" >&2
        die "$proto generation failed with status $status (log kept at $outdir/.regen.log)"
    fi

    warnings="$(grep -c WARNING "$outdir/.regen.log" || true)"
    rm -f "$outdir/.regen.log" "$outdir/Makefile.am.libasncodec"
    cp "$cmakelists" "$cmakelists_dest"
    rm -f "$cmakelists"
    cmakelists=""

    stray="$(find "$outdir" -maxdepth 1 -type f ! -name "${prefix}*" ! -name CMakeLists.txt -printf '%f\n')"
    [[ -z "$stray" ]] || die "$proto: unprefixed output would shadow another tree: $stray"

    printf '    %d files, %s compiler warnings\n' \
        "$(find "$outdir" -maxdepth 1 -name "${prefix}*" | wc -l)" "$warnings"
done

if ! diff -rq "$runtime_before/asn1c" src/asn/asn1c > /dev/null; then
    printf 'regen_asn1: NOTE: src/asn/asn1c changed. That is expected only when the\n' >&2
    printf '            skeletons in %s changed. Review the diff.\n' "$ASN1C_REPO" >&2
fi

printf '\nDone. Now: cmake --build build && tools/check_asn1_runtime.sh\n'
